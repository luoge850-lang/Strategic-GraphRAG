"""Conservative parser for NT$ consolidated financial-performance summaries.

Separate facing printed pages before reading rows. Never infer a currency
from the issuer name or mix consolidated with unconsolidated amounts.
Unsupported table layouts produce no accepted facts.
"""
import json,re
LABELS = {'Net Revenue':'REVENUE','Cost of Revenue':'COST_OF_REVENUE',
          'Other Operating Income and Expenses, Net':'OTHER_OPERATING_INCOME_EXPENSE_NET',
          'Other Comprehensive Income (Loss), Net':'OTHER_COMPREHENSIVE_GAIN_NET',
          'Other Comprehensive Income, Net':'OTHER_COMPREHENSIVE_GAIN_NET',
          'Other Comprehensive Gain (Loss), Net':'OTHER_COMPREHENSIVE_GAIN_NET',
          'Other Comprehensive Gain (Loss), Net of Income Tax':'OTHER_COMPREHENSIVE_GAIN_NET',
          'Non-operating Income and Expenses':'NON_OPERATING_INCOME',
          'Gross Profit':'GROSS_PROFIT','Operating Expenses':'OPERATING_COST',
          'Income from Operations':'OPERATING_INCOME','Income before Income Tax':'PRETAX_INCOME',
          'Income Tax Expenses':'INCOME_TAX_EXPENSE','Net Income':'NET_INCOME',
          'Total Net Income Attributable to Shareholders of the Parent':'PARENT_NET_INCOME'}
BALANCES={'Current Assets':'TOTAL_CURRENT_ASSETS','Total Assets':'TOTAL_ASSETS',
          'Current Liabilities':'TOTAL_CURRENT_LIABILITIES','Total Liabilities':'TOTAL_LIABILITIES',
          'Retained Earnings':'RETAINED_EARNINGS','Total Equity':'TOTAL_EQUITY',
          'Long-term Investments (Note 1)':'LONG_TERM_INVESTMENTS',
          'Property, Plant and Equipment':'PROPERTY_PLANT_EQUIPMENT',
          'Right-of-use Assets':'RIGHT_OF_USE_ASSETS','Intangible Assets':'INTANGIBLE_ASSETS',
          'Other Assets (Note 2)':'OTHER_ASSETS','Noncurrent Liabilities':'NONCURRENT_LIABILITIES',
          'Capital Stock':'CAPITAL_STOCK','Capital Surplus':'CAPITAL_SURPLUS',
          'Others Equity':'OTHER_EQUITY','Equity Attributable to Shareholders of the Parent':'PARENT_EQUITY'}

def fact(company,filename,year,metric,label,values,evidence,bbox,statement,table):
    return dict(source=company,source_category='Company',target=metric,target_category='FinancialMetric',
        relation='REPORTS_METRIC',causal_strength='DISCLOSED_ONLY',causal_form='FINANCIAL_RELATION',
        evidence_sentence=evidence,metric_values_json=json.dumps(values),metric_unit='TWD thousands',
        unit='TWD thousands',currency='TWD',scale='thousands',row_label=label,source_row_id=label,
        table_name=table,statement_type=statement,source_section='MD_AND_A',report_period=f'FY{year}',
        comparability_status='SAME_TABLE',source_filing=filename,physical_bbox=bbox,
        financial_basis='ACTUAL_REPORTED',basis_evidence='Consolidated\nUnit: NT$ thousands',
        source_row=evidence,table_context=evidence)

def cash_flow(half,text,company,filename,filing_year,bbox):
    """Validate actual header columns and the consolidated six-value row.

    Table cells can lose the first amount at a border, so values come from the
    complete original row. Unknown/reordered headers are mapped, never assumed.
    """
    section=re.split(r'(?m)^Unconsolidated\s*$',text)[0]
    if not re.search(r'Cash Flow\s+Consolidated\s+Unit: NT\$ thousands',section):return []
    tables=half.extract_tables()
    if not tables or not tables[0]:return []
    headers=[re.sub(r'\s+',' ',str(x or '')).strip() for x in tables[0][0]]
    if len(headers)!=8 or headers[6]!='Remedy for Liquidity Shortfall':return []
    descriptions=[]
    flow_labels={'Net Cash Provided by Operating Activities':'OPERATING_CASH_FLOW',
                 'Net Cash Used in Investing Activities':'INVESTING_CASH_FLOW',
                 'Net Cash Used in Financing Activities':'FINANCING_CASH_FLOW',
                 'Net Cash Generated by Financing Activities':'FINANCING_CASH_FLOW',
                 'Effect of Exchange Rate Changes on Cash and Cash Equivalents':'EXCHANGE_RATE_CASH_EFFECT'}
    for h in headers[:6]:
        m=re.fullmatch(r'Cash Balance 12/31/(20\d{2})',h)
        if m:descriptions.append(('CASH_AND_CASH_EQUIVALENTS','Cash Balance',int(m.group(1))));continue
        matched=False
        for label,metric in flow_labels.items():
            m=re.fullmatch(re.escape(label)+r' in (20\d{2})',h)
            if m:descriptions.append((metric,label,int(m.group(1))));matched=True;break
        if not matched:return []
    flow_years={y for m,_,y in descriptions if m!='CASH_AND_CASH_EQUIVALENTS'}
    cash_years=sorted(y for m,_,y in descriptions if m=='CASH_AND_CASH_EQUIVALENTS')
    if len(flow_years)!=1 or len(cash_years)!=2 or cash_years!=[next(iter(flow_years))-1,next(iter(flow_years))]:return []
    token=r'\(?-?\d[\d,]*\)?'
    matches=[line.strip() for line in section.splitlines() if re.fullmatch(r'(?:'+token+r'\s+){6}None\s+None',line.strip())]
    if len(matches)!=1:return []
    numbers=matches[0].split()[:6];grouped={}
    for (metric,label,year),raw in zip(descriptions,numbers):
        value=('-' if raw.startswith('(') else '')+raw.strip('()').replace(',','')
        grouped.setdefault((metric,label),[]).append(dict(period=str(year),value=value))
    evidence='Cash Flow\nConsolidated\nUnit: NT$ thousands\n'+' | '.join(headers[:6])+'\n'+matches[0]
    return [fact(company,filename,filing_year,m,l,v,evidence,bbox,'CASH_FLOW_STATEMENT','Consolidated cash flow') for (m,l),v in grouped.items()]
def extract(page, *, company_id, filename, filing_year):
    result=[]
    for bbox in [(0,0,page.width/2,page.height),(page.width/2,0,page.width,page.height)]:
        half=page.crop(bbox)
        text=half.extract_text() or ''
        result.extend(cash_flow(half,text,company_id,filename,filing_year,bbox))
        if not re.search(r'(?m)^Consolidated\s*$',text) or re.search(r'(?m)^Unconsolidated\s*$',text):continue
        if 'Unit: NT$ thousands' not in text:continue
        header=re.search(r'Item\s+(20\d{2})\s+(20\d{2})\s+Difference\s+%',text)
        if not header:continue
        years=[int(header.group(1)),int(header.group(2))]
        for line in text.splitlines():
            for label,metric in {**LABELS,**BALANCES}.items():
                m=re.fullmatch(re.escape(label)+r'\s+(\(?-?[\d,]+\)?)\s+(\(?-?[\d,]+\)?)\s+\(?-?[\d,]+\)?\s+(?:-?[\d.]+%|NM)',line.strip())
                if not m:continue
                vals=[('-' if v.startswith('(') else '')+v.strip('()').replace(',','') for v in m.groups()]
                balance=label in BALANCES
                result.append(fact(company_id,filename,filing_year,metric,label,
                    [dict(period=str(y),value=v) for y,v in zip(years,vals)],
                    'Consolidated\nUnit: NT$ thousands\n'+header.group(0)+'\n'+line.strip(),bbox,
                    'BALANCE_SHEET' if balance else 'INCOME_STATEMENT',
                    'Consolidated financial status' if balance else 'Consolidated financial performance'))
    return result
