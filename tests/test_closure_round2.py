import copy
import pytest
from strategic_graphrag.engine.query_understanding import parse_query
from deployment.slot_score_20261016 import score
from tests.test_slot_scorer_integrity import fixture

@pytest.mark.parametrize('label',['accounts receivable, net','accounts receivable net'])
@pytest.mark.parametrize('company',['NVIDIA','TSMC'])
def test_net_receivable_alias_is_one_slot(label,company):
    plan=parse_query(f'What were {company} {label} in fiscal 2023?')
    assert not plan.ambiguity
    assert len(plan.requested_facts)==1
    assert plan.requested_facts[0]['metric_id']=='ACCOUNTS_RECEIVABLE'

def test_comma_net_does_not_hide_unknown_or_second_metric():
    plan=parse_query('What were NVIDIA accounts receivable, net, employee satisfaction in fiscal 2023?')
    assert plan.ambiguity
    plan=parse_query('What were NVIDIA accounts receivable, net income in fiscal 2023?')
    assert len(plan.requested_facts)==2

def test_correct_partial_is_incomplete_but_not_wrong_success():
    response,label=fixture()
    label['slots'].append(copy.deepcopy(label['slots'][0]))
    response['answer_status']='PARTIALLY_ANSWERED'
    result=score(response,label,build_id='build_x')
    assert not result['request_complete']
    assert not result['severe_wrong_success']

def test_generated_financing_header_keeps_negative_sign():
    import json
    from strategic_graphrag.pipeline.consolidated_ntd_table import cash_flow
    class Half:
        def extract_tables(self):
            return [[['Cash Balance 12/31/2022','Net Cash Provided by Operating Activities in 2023',
                      'Net Cash Used in Investing Activities in 2023','Net Cash Generated by Financing Activities in 2023',
                      'Effect of Exchange Rate Changes on Cash and Cash Equivalents in 2023','Cash Balance 12/31/2023',
                      'Remedy for Liquidity Shortfall',None]]]
    facts=cash_flow(Half(),'Cash Flow\nConsolidated\nUnit: NT$ thousands\n100 200 (30) (40) (5) 225 None None',
                    'TEST_COMPANY','test.pdf',2023,[0,0,100,100])
    financing=next(f for f in facts if f['target']=='FINANCING_CASH_FLOW')
    assert json.loads(financing['metric_values_json'])==[dict(period='2023',value='-40')]
    assert 'Generated by Financing' in financing['evidence_sentence']
